class Patterns(Flowable):
    """Concept drawings only; no numerical signal criteria are illustrated."""

    def __init__(self, breaker=False):
        super().__init__(); self.width = CW; self.height = 178; self.breaker = breaker

    def draw(self):
        c = self.canv; pw = (CW - 14) / 2
        for side in (0, 1):
            x = side * (pw + 14); tone = colors.HexColor('#2F9E44') if side == 0 else colors.HexColor('#D64545')
            c.setFillColor(tint(tone, .08)); c.roundRect(x, 0, pw, 172, 10, fill=1, stroke=0)
            c.setFillColor(tone); c.setFont('MGB', 10.5)
            c.drawString(x + 14, 150, '매수 올존 · 마이크로 더블바텀' if side == 0 else '매도 올존 · 마이크로 더블탑')
            points = [(0, 99), (.20, 49), (.44, 88), (.67, 46), (.94, 108)]
            if self.breaker: points = [(0, 105), (.20, 63), (.44, 95), (.67, 35), (.94, 108)]
            if side == 1: points = [(a, 143 - b) for a, b in points]
            path = c.beginPath()
            for i, (a, b) in enumerate(points[:4]):
                px = x + 18 + a * (pw - 38); py = 22 + b * .8
                (path.moveTo if i == 0 else path.lineTo)(px, py)
            c.setStrokeColor(tone); c.setLineWidth(2.6); c.drawPath(path)
            a, b = points[3]; px = x + 18 + a * (pw - 38); py = 22 + b * .8
            na, nb = points[4]
            c.setStrokeColor(MUTED); c.setLineWidth(1.5); c.setDash(3, 3)
            c.line(px, py, x + 18 + na * (pw - 38), 22 + nb * .8); c.setDash()
            c.setFillColor(tone); c.circle(px, py, 4.6, fill=1, stroke=0)
            c.setFont('MGB', 8.4)
            c.drawString(x + pw - 104, py - 16 if side == 0 else py + 10, '알림: 우측 저점' if side == 0 else '알림: 우측 고점')
            if self.breaker:
                base = 22 + (51 if side == 0 else 143 - 51) * .8
                c.setDash(4, 3); c.setStrokeColor(MUTED); c.setLineWidth(.8)
                c.line(x + 12, base, x + pw - 12, base); c.setDash()
                c.setFillColor(MUTED); c.setFont('MG', 8)
                c.drawString(x + 14, base - 12 if side == 0 else base + 6, '앞전 저점 기준' if side == 0 else '앞전 고점 기준')
            c.setFillColor(MUTED); c.setFont('MG', 8.4)
            c.drawString(x + 14, 9, '점선: 알림 뒤 실제 반전을 확인할 구간')


