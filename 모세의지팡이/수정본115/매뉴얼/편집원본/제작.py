def note(title,text):
    cell=Paragraph('<b>'+escape(title)+'</b><br/>'+escape(text).replace('\n','<br/>'),styles['cell'])
    t=Table([[cell]],colWidths=[CW],hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,-1),LIGHT),('LINEBEFORE',(0,0),(0,-1),3,TEAL),
        ('LEFTPADDING',(0,0),(-1,-1),12),('RIGHTPADDING',(0,0),(-1,-1),12),
        ('TOPPADDING',(0,0),(-1,-1),9),('BOTTOMPADDING',(0,0),(-1,-1),9)]))
    return [t,Spacer(1,9)]
def steps(items):
    cells=[]
    for i,(title,text) in enumerate(items,1):
        cells.append([Paragraph(f'<b><font color="#176FC1">{i:02}</font></b>',styles['body']),
            Paragraph('<b>'+escape(title)+'</b><br/>'+escape(text),styles['body'])])
    t=Table(cells,colWidths=[30,CW-30],hAlign='LEFT')
    t.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),0),
        ('RIGHTPADDING',(0,0),(-1,-1),6),('TOPPADDING',(0,0),(-1,-1),2),('BOTTOMPADDING',(0,0),(-1,-1),4)]))
    return [t,Spacer(1,5)]
